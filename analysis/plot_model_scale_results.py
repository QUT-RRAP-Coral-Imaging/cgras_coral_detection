#!/usr/bin/env python3

import argparse
import csv
import os
from typing import List, Dict

import matplotlib.pyplot as plt


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Plot YOLO model scale comparison results from CSV.")
    parser.add_argument("--csv", required=True, help="Path to metrics CSV generated by scale training script")
    parser.add_argument("--out-dir", required=True, help="Directory to save output graphs")
    return parser.parse_args()


def model_sort_key(model_name: str) -> int:
    order = {
        "yolov8n.pt": 0,
        "yolov8s.pt": 1,
        "yolov8m.pt": 2,
        "yolov8l.pt": 3,
        "yolov8x.pt": 4,
    }
    return order.get(model_name.strip(), 999)


def load_rows(csv_path: str) -> List[Dict[str, str]]:
    with open(csv_path, "r", encoding="utf-8") as file:
        rows = list(csv.DictReader(file))
    if not rows:
        raise ValueError(f"No data rows found in CSV: {csv_path}")
    return sorted(rows, key=lambda row: model_sort_key(row.get("model_size", "")))


def to_float(row: Dict[str, str], key: str) -> float:
    value = row.get(key, "")
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def save_metric_bars(labels: List[str], rows: List[Dict[str, str]], out_dir: str) -> None:
    metric_keys = ["map50", "map50_95", "precision", "recall"]
    metric_titles = ["mAP50", "mAP50-95", "Precision", "Recall"]
    colors = ["#1f77b4", "#ff7f0e", "#2ca02c", "#d62728"]

    fig, axes = plt.subplots(2, 2, figsize=(12, 8))
    axes = axes.flatten()

    for i, (metric_key, metric_title) in enumerate(zip(metric_keys, metric_titles)):
        values = [to_float(row, metric_key) for row in rows]
        ax = axes[i]
        bars = ax.bar(labels, values, color=colors[i])
        ax.set_title(metric_title)
        ax.set_ylim(0, max(1.0, max(values) * 1.1 if values else 1.0))
        ax.set_ylabel("Score")
        ax.grid(axis="y", alpha=0.3)
        ax.tick_params(axis="x", rotation=20)

        for bar, val in zip(bars, values):
            ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.01, f"{val:.3f}",
                    ha="center", va="bottom", fontsize=8)

    fig.suptitle("YOLOv8 Model Scale Comparison")
    fig.tight_layout()
    fig.savefig(os.path.join(out_dir, "model_metrics_grid.png"), dpi=300)
    plt.close(fig)


def save_map_curve(labels: List[str], rows: List[Dict[str, str]], out_dir: str) -> None:
    map50 = [to_float(row, "map50") for row in rows]
    map50_95 = [to_float(row, "map50_95") for row in rows]

    plt.figure(figsize=(9, 5))
    plt.plot(labels, map50, marker="o", label="mAP50")
    plt.plot(labels, map50_95, marker="o", label="mAP50-95")
    plt.title("mAP by YOLOv8 Model Scale")
    plt.xlabel("Model")
    plt.ylabel("Score")
    plt.ylim(0, 1.0)
    plt.grid(alpha=0.3)
    plt.legend()
    plt.tight_layout()
    plt.savefig(os.path.join(out_dir, "map_comparison.png"), dpi=300)
    plt.close()


def save_table_csv(rows: List[Dict[str, str]], out_dir: str) -> None:
    out_path = os.path.join(out_dir, "model_metrics_sorted.csv")
    with open(out_path, "w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    args = parse_args()
    os.makedirs(args.out_dir, exist_ok=True)

    rows = load_rows(args.csv)
    labels = [row.get("model_size", "unknown") for row in rows]

    save_metric_bars(labels, rows, args.out_dir)
    save_map_curve(labels, rows, args.out_dir)
    save_table_csv(rows, args.out_dir)

    print(f"Saved graphs to: {args.out_dir}")


if __name__ == "__main__":
    main()
